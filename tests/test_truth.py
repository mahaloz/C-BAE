def test_concurrent_builders_share_one_complete_index(tmp_path: Path) -> None:
    truth_path = tmp_path / "truth.json"
    truth_path.write_text(
        json.dumps(
            {
                f"0x{address:x}": {"name": f"function_{address}x", "mangled_name": None}
                for address in range(1, 101)
            }
        ),
        encoding="utf-8",
    )
    checksum = _sha256(truth_path)
    cache = tmp_path / "private"
    context = multiprocessing.get_context("spawn")
    queue = context.Queue()
    processes = [
        context.Process(
            target=_build_worker,
            args=(str(truth_path), checksum, str(cache), queue),
        )
        for _ in range(3)
    ]
    for process in processes:
        process.start()
    results = [queue.get(timeout=30) for _ in processes]
    for process in processes:
        process.join(timeout=30)

    assert results == [("ok", 100)] * 3
    assert all(process.exitcode == 0 for process in processes)


def test_duplicate_normalized_truth_address_is_rejected(tmp_path: Path) -> None:
    truth_path = tmp_path / "duplicates.json"
    truth_path.write_text(
        '{"0x1":{"name":"one"},"0X01":{"name":"also one"}}',
        encoding="utf-8",
    )

    with pytest.raises(TruthIndexError, match="duplicate raw or normalized"):
        build_truth_index(
            truth_path,
            tmp_path / "cache",
            truth_sha256=_sha256(truth_path),
            image_base=0,
            address_space="rva",
        )


def test_truth_checksum_mismatch_is_fatal(tmp_path: Path) -> None:
    truth_path = tmp_path / "truth.json"
    truth_path.write_text("{}", encoding="utf-8")

    with pytest.raises(TruthIndexError, match="SHA-256 mismatch"):
        build_truth_index(
            truth_path,
            tmp_path / "cache",
            truth_sha256="0" * 64,
            image_base=0,
            address_space="rva",
        )


